//! The gateway's side of a task's images: recording them, telling every
//! view, and serving only what was recorded.
#![allow(clippy::disallowed_methods)]

use std::path::PathBuf;

use arkavo_protocol::types::MessagePart;
use arkavo_test_macros::spec;
use axum::body::to_bytes;
use serde_json::json;
use tokio::sync::mpsc;

use super::*;
use crate::gateway::ConnectionInfo;

fn answer() -> Vec<MessagePart> {
    vec![
        MessagePart::Text {
            content: "Your gold coin sprite is attached.".into(),
        },
        MessagePart::Data {
            schema: MANIFEST_SCHEMA.into(),
            content: json!({}),
        },
    ]
}

/// A fetcher that writes one PNG and reports it.
struct OneImage(PathBuf);

#[async_trait::async_trait]
impl AssetFetcher for OneImage {
    async fn fetch(
        &self,
        _task_id: &str,
        parts: &[MessagePart],
    ) -> Result<Vec<FetchedAsset>, String> {
        assert!(references_assets(parts));
        std::fs::write(&self.0, b"\x89PNG fake").map_err(|e| e.to_string())?;
        Ok(vec![FetchedAsset {
            name: "coin.png".into(),
            path: self.0.clone(),
            width: 1024,
            height: 1024,
            has_alpha: true,
            bytes: 9,
            license: "Generated by m6 with qwen-image".into(),
        }])
    }
}

/// A view listening on the gateway, as a browser's socket does.
async fn view(
    connections: &Arc<RwLock<HashMap<String, ConnectionInfo>>>,
) -> mpsc::Receiver<AgUiEvent> {
    let (tx, rx) = mpsc::channel(8);
    connections.write().await.insert(
        "view".into(),
        ConnectionInfo {
            _ws_tx: tx,
            _agent_id: None,
            subscriptions: Vec::new(),
            current_plan: None,
            current_prompt: None,
        },
    );
    rx
}

/// AGUI-025: the images an agent delivers are fetched, recorded on the
/// task and sent to every view with the output it already shows.
#[spec("AGUI-025")]
#[tokio::test]
async fn delivered_images_reach_every_view_with_the_task() {
    let dir = tempfile::tempdir().unwrap();
    let state = crate::test_support::app_state();
    state.task_store.write().await.insert(
        "t1".into(),
        crate::test_support::tracked_task("t1", "completed", "2026-10-18T00:00:00Z"),
    );
    let mut rx = view(&state.connections).await;
    let fetcher: Arc<dyn AssetFetcher> = Arc::new(OneImage(dir.path().join("coin.png")));

    deliver(
        Some(&fetcher),
        "t1",
        &answer(),
        &state.task_store,
        &state.connections,
    )
    .await;

    let fetching = serde_json::to_value(rx.recv().await.unwrap()).unwrap();
    assert_eq!(fetching["assetNote"], "Fetching images from the agent");
    let delivered = serde_json::to_value(rx.recv().await.unwrap()).unwrap();
    assert_eq!(delivered["result"], "Your gold coin sprite is attached.");
    assert_eq!(delivered["assets"][0]["url"], "/assets/t1/coin.png");
    assert_eq!(delivered["assets"][0]["hasAlpha"], true);
    assert!(delivered.get("assetNote").is_none(), "{delivered}");
}

/// AGUI-025: a build that cannot fetch says where the images are rather
/// than showing nothing.
#[spec("AGUI-025")]
#[tokio::test]
async fn without_a_fetcher_the_view_hears_the_images_stayed_on_the_agent() {
    let state = crate::test_support::app_state();
    state.task_store.write().await.insert(
        "t1".into(),
        crate::test_support::tracked_task("t1", "completed", "2026-10-18T00:00:00Z"),
    );
    let mut rx = view(&state.connections).await;

    deliver(None, "t1", &answer(), &state.task_store, &state.connections).await;

    let event = serde_json::to_value(rx.recv().await.unwrap()).unwrap();
    assert!(
        event["assetNote"]
            .as_str()
            .unwrap()
            .contains("stayed on the agent")
    );
}

/// AGUI-025: only a file a fetch recorded on the task is served, never a
/// path the request names.
#[spec("AGUI-025")]
#[tokio::test]
async fn only_recorded_images_are_served() {
    let dir = tempfile::tempdir().unwrap();
    let state = crate::test_support::app_state();
    state.task_store.write().await.insert(
        "t1".into(),
        crate::test_support::tracked_task("t1", "completed", "2026-10-18T00:00:00Z"),
    );
    let fetcher: Arc<dyn AssetFetcher> = Arc::new(OneImage(dir.path().join("coin.png")));
    deliver(
        Some(&fetcher),
        "t1",
        &answer(),
        &state.task_store,
        &state.connections,
    )
    .await;

    let served = asset_handler(State(state.clone()), Path(("t1".into(), "coin.png".into()))).await;
    assert_eq!(served.status(), StatusCode::OK);
    assert_eq!(served.headers()[header::CONTENT_TYPE], "image/png");
    assert_eq!(
        &to_bytes(served.into_body(), 1024).await.unwrap()[..],
        b"\x89PNG fake"
    );

    for (task_id, name) in [
        ("t1", "../coin.png"),
        ("t1", "other.png"),
        ("t2", "coin.png"),
    ] {
        let refused =
            asset_handler(State(state.clone()), Path((task_id.into(), name.into()))).await;
        assert_eq!(refused.status(), StatusCode::NOT_FOUND, "{task_id}/{name}");
    }
}

